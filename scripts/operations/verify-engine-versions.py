#!/usr/bin/env python3
"""@type script @purpose Keep the control-plane's pinned engine hashes aligned with shipped Python sources."""
from __future__ import annotations
import argparse
import hashlib
from pathlib import Path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    evaluation = hashlib.sha256((root / "scripts/diagnostics/evaluate-frame-objects.py").read_bytes()).hexdigest()
    package = root / "backend/video_semantic_extractor"
    sampling = hashlib.sha256(b"pipeline.py\0" + (package / "pipeline.py").read_bytes() + b"sampling_runner.py\0" + (package / "sampling_runner.py").read_bytes()).hexdigest()
    content = f'/** Generated by scripts/operations/verify-engine-versions.py --write. */\nexport const EVALUATION_IMPLEMENTATION_VERSION = "managed-object-evaluation.v1@sha256:{evaluation}";\nexport const SAMPLING_IMPLEMENTATION_VERSION = "video-semantic-extractor@1.0.0@sha256:{sampling}";\n'
    target = root / "workers/control-plane/src/engine-versions.ts"
    if args.write:
        target.write_text(content, encoding="utf-8")
    elif not target.is_file() or target.read_text(encoding="utf-8") != content:
        parser.error("engine sources changed; run this command with --write and review the version update")
    print("Engine implementation hashes verified")


if __name__ == "__main__":
    main()
